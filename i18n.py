LANG = "uk"


def set_language(lang: str) -> None:
    global LANG
    LANG = lang if lang in TEXT else "uk"


def t(key: str, **kw) -> str:
    s = TEXT[LANG].get(key) or TEXT["en"].get(key) or key
    return s.format(**kw) if kw else s


def th(key: str, **kw) -> str:
    """Переклад, безпечний для HTML Telegram (екранує &, <, >)."""
    import html
    return html.escape(t(key, **kw), quote=False)


def asset_name(asset: dict) -> str:
    if asset.get("name"):
        return asset["name"]
    return ASSET_NAMES.get(asset["symbol"], {}).get(LANG, asset["symbol"])
